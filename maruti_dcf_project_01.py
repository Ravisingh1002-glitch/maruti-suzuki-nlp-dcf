import pandas as pd
import PyPDF2
from transformers import pipeline

# 1. Initialize FinBERT
print("Loading FinBERT...")
nlp = pipeline("sentiment-analysis", model="ProsusAI/finbert")

# 2. Hardcode the exact filenames in chronological order
file_list = [
    "q2 ft 26.pdf",     # Oct 2025
    "q3 fy 26 .pdf",    # Jan 2026
    "q4 fy 26.pdf",     # Apr 2026
    "q1 ft27.pdf"       # Jul 2026
]

all_results = []

# 3. Loop through your specific files directly
for filename in file_list:
    print(f"Processing {filename}...")

    # Extract text directly from the current directory
    with open(filename, 'rb') as pdf_file:
        pdf_reader = PyPDF2.PdfReader(pdf_file)
        full_text = "".join([page.extract_text() for page in pdf_reader.pages])

    # Chunk into sentences
    sentences = [s for s in full_text.split('. ') if len(s.split()) > 5]

    # Run NLP on the sentences
    results = nlp(sentences)

    # Clean up the quarter names for the final presentation table
    clean_quarter_name = filename.replace('.pdf', '').strip().upper().replace('FT', 'FY')

    # Tag each sentence with its corresponding quarter
    for res, sentence in zip(results, sentences):
        res['Quarter'] = clean_quarter_name
        res['Statement'] = sentence
        all_results.append(res)

# 4. Aggregate the data into a Master Trendline
df = pd.DataFrame(all_results)
trend_summary = df.groupby(['Quarter', 'label']).size().unstack(fill_value=0)

# Reorder index to ensure chronological output
trend_summary = trend_summary.reindex(["Q2 FY 26", "Q3 FY 26", "Q4 FY 26", "Q1 FY27"])

print("\n--- Maruti Suzuki Sentiment Trend Across Quarters ---")
print(trend_summary)